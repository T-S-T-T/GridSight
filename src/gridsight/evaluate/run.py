"""End-to-end model jobs: build features, validate with walk-forward folds, score the locked test
period, compare with AEMO, train and register the production models."""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import pandas as pd

from gridsight import storage
from gridsight.config import get_settings, models_config
from gridsight.evaluate.backtest import (
    Fold,
    compare_with_aemo,
    run_backtest,
    score,
    split_test_period,
    walk_forward_folds,
)
from gridsight.features.build import build_features, feature_columns
from gridsight.models.base import ModelCard, list_versions, new_version, save_model, set_stage
from gridsight.models.tasks import TASKS, fit_model, model_factories

log = logging.getLogger(__name__)


# ---------------------------------------------------------------- features


def build_and_store_features(horizons: tuple[int, ...] | None = None, issue_every: str = "30min") -> pd.DataFrame:
    s = get_settings()
    cfg = models_config()
    horizons = horizons or tuple(sorted(set(cfg["horizons"]["demand"]) | set(cfg["horizons"]["price"])))
    price, demand = storage.read("dispatch_price"), storage.read("region_demand")
    if price.empty or demand.empty:
        raise RuntimeError("no silver data: run `gridsight synth` or `gridsight backfill` first")
    feats = build_features(
        price,
        demand,
        weather=storage.read("weather_forecast"),
        predispatch=storage.read("predispatch"),
        horizons=horizons,
        spike_threshold=s.spike_threshold,
        issue_every=issue_every,
    )
    storage.write(feats, "features_30m", layer="gold")
    log.info("built %d feature rows", len(feats))
    return feats


def load_features() -> pd.DataFrame:
    return storage.read("features_30m", layer="gold")


# ---------------------------------------------------------------- evaluation


@dataclass
class TaskResult:
    task: str
    validation: pd.DataFrame
    test: pd.DataFrame
    test_by_horizon: pd.DataFrame
    vs_aemo: pd.DataFrame
    vs_aemo_by_horizon: pd.DataFrame
    test_predictions: pd.DataFrame = field(repr=False)


def evaluate_task(
    feats: pd.DataFrame,
    task_name: str,
    gbm_params: dict[str, Any] | None = None,
    backtest_cfg: dict[str, int] | None = None,
    test_start: str | None = None,
) -> TaskResult:
    cfg = models_config()
    task = TASKS[task_name]
    bt = {**cfg["backtest"], **(backtest_cfg or {})}
    params = {**cfg["lightgbm"], **(gbm_params or {})}
    features = feature_columns(feats)
    kw = {
        "quantiles": tuple(cfg["quantiles"]),
        "gbm_params": params,
        "alpha": cfg.get("conformal_alpha", 0.2),
        "spike_threshold": get_settings().spike_threshold,
    }
    horizons = set(cfg["horizons"].get(task_name, cfg["horizons"]["price"]))
    f = feats[feats["horizon"].isin(horizons)] if task_name != "spike" else feats[feats["horizon"] <= 2]
    if f.empty:
        f = feats

    t0 = split_test_period(f["issued_utc"], test_start or cfg.get("test_start"), bt["min_train_days"])
    pre = f[f["issued_utc"] < t0]
    folds = walk_forward_folds(pre["issued_utc"], bt["n_folds"], bt["fold_days"], bt["gap_days"], bt["min_train_days"], end=t0)
    val_pred = run_backtest(f, task, features, folds, **kw)
    test_fold = Fold(-1, t0 - pd.Timedelta(days=bt["gap_days"]), t0, f["issued_utc"].max() + pd.Timedelta("30min"))
    test_pred = run_backtest(f, task, features, [test_fold], **kw)

    return TaskResult(
        task=task_name,
        validation=score(val_pred, task) if not val_pred.empty else pd.DataFrame(),
        test=score(test_pred, task),
        test_by_horizon=score(test_pred, task, by=["horizon"]),
        vs_aemo=compare_with_aemo(test_pred, task),
        vs_aemo_by_horizon=compare_with_aemo(test_pred, task, by=["horizon"]),
        test_predictions=test_pred,
    )


def _fmt(df: pd.DataFrame) -> str:
    if df.empty:
        return "_no rows_"
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:,.4g}")
    cols = list(d.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in d.itertuples(index=False)]
    return "\n".join(lines)


def write_results(results: dict[str, TaskResult], out_dir: Path | None = None) -> Path:
    out_dir = out_dir or get_settings().reports_dir / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    md = ["# GridSight results (generated by `gridsight evaluate`)", ""]
    for name, r in results.items():
        r.test.to_csv(out_dir / f"{name}_test.csv", index=False)
        r.test_by_horizon.to_csv(out_dir / f"{name}_test_by_horizon.csv", index=False)
        r.validation.to_csv(out_dir / f"{name}_validation.csv", index=False)
        r.vs_aemo.to_csv(out_dir / f"{name}_vs_aemo.csv", index=False)
        r.vs_aemo_by_horizon.to_csv(out_dir / f"{name}_vs_aemo_by_horizon.csv", index=False)
        r.test_predictions.to_parquet(out_dir / f"{name}_test_predictions.parquet", index=False)
        md += [f"## {name.title()}", "", "Locked test period:", "", _fmt(r.test), ""]
        if not r.vs_aemo.empty:
            md += ["Against AEMO pre-dispatch (same rows, Diebold-Mariano test):", "", _fmt(r.vs_aemo), ""]
        if not r.validation.empty:
            md += ["Walk-forward validation:", "", _fmt(r.validation), ""]
    path = out_dir / "results.md"
    path.write_text("\n".join(md), encoding="utf-8")
    return path


def evaluate_all(
    feats: pd.DataFrame | None = None,
    tasks: tuple[str, ...] = ("demand", "price", "spike"),
    **kwargs: Any,
) -> dict[str, TaskResult]:
    feats = feats if feats is not None else load_features()
    if feats.empty:
        raise RuntimeError("no features: run `gridsight features` first")
    results = {t: evaluate_task(feats, t, **kwargs) for t in tasks}
    write_results(results)
    return results


# ---------------------------------------------------------------- production training


def train_production(
    feats: pd.DataFrame | None = None,
    tasks: tuple[str, ...] = ("demand", "price", "spike"),
    gbm_params: dict[str, Any] | None = None,
    metrics: dict[str, dict[str, float]] | None = None,
    promote_if_first: bool = True,
) -> dict[str, ModelCard]:
    """Fit the main model of each task on every labelled row and register it as Staging.
    The first version of a model is promoted to Production automatically."""
    feats = feats if feats is not None else load_features()
    cfg = models_config()
    features = feature_columns(feats)
    params = {**cfg["lightgbm"], **(gbm_params or {})}
    cards = {}
    for t in tasks:
        task = TASKS[t]
        f = feats[feats[task.target].notna()]
        if t == "spike":
            f = f[f["horizon"] <= 2]
        factories = model_factories(task, features, tuple(cfg["quantiles"]), params, cfg.get("conformal_alpha", 0.2),
                                    get_settings().spike_threshold, include_baselines=False)
        name, make = next(iter(factories.items()))
        model = fit_model(make(), f, f[task.target], order=f["issued_utc"])
        card = ModelCard(
            name=name,
            version=new_version(),
            task=t,
            created_utc=pd.Timestamp.now(tz="UTC").isoformat(),
            features=features,
            metrics=(metrics or {}).get(t, {}),
            params={**params, "train_rows": len(f), "data_end": str(f["target_utc"].max())},
        )
        save_model(model, card)
        if promote_if_first and not any(c.stage == "Production" for c in list_versions(name)):
            set_stage(name, card.version, "Production")
            card.stage = "Production"
        cards[t] = card
        log.info("registered %s %s (%s)", name, card.version, card.stage)
    return cards
